function buildEmails(): EmailMessage[] {
  const emails: EmailMessage[] = rawEmails.map((raw) => {
    const isIn = raw.direction === 'in'
    return {
      ...raw,
      from: isIn ? raw.customerEmail : SERVICE_EMAIL,
      to: isIn ? SERVICE_EMAIL : raw.customerEmail,
      alsNo: extractAlsFromText(`${raw.subject} ${raw.body}`) || null,
      replied: true,
    }
  })
  for (const m of emails) {
    if (m.direction === 'in') {
      m.replied = emails.some(
        (e) =>
          e.threadId === m.threadId &&
          e.direction === 'out' &&
          e.sentAt > m.sentAt,
      )
    }
  }
  return emails
}

